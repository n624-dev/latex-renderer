export type RendererMcpMessage = keyof typeof rendererMcpEnglishMessages;

type TranslationValues = Readonly<
  Record<string, string | number | boolean | null | undefined>
>;
export type RendererMcpTranslate = (
  key: RendererMcpMessage,
  values?: TranslationValues,
) => string;

export const rendererMcpEnglishText: RendererMcpTranslate = (
  key,
  values = {},
) => interpolateRendererMcpText(rendererMcpEnglishMessages[key], values);

export function interpolateRendererMcpText(
  message: string,
  values: TranslationValues,
): string {
  return message.replaceAll(
    /\{([a-zA-Z][a-zA-Z0-9]*)\}/g,
    (match, name: string) =>
      Object.hasOwn(values, name) ? String(values[name]) : match,
  );
}
